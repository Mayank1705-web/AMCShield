def save_cw():
    path = RESULTS_DIR / "cw_results.csv"

    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)

        writer.writerow([
            "snr",
            "clean_accuracy",
            "cw_accuracy",
            "attack_success_rate",
            "mean_linf",
            "max_linf",
            "mean_l2",
            "max_l2",
        ])

        for row in cw:
            snr, clean, attack, asr, mean_linf, max_linf, mean_l2, max_l2 = row

            writer.writerow([
                snr,
                clean / 100,
                attack / 100,
                asr / 100,
                mean_linf,
                max_linf,
                mean_l2,
                max_l2,
            ])

    print(f"Saved: {path}")


