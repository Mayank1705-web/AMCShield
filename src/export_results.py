def save_standard(filename, data, attack_name):
    path = RESULTS_DIR / filename

    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)

        writer.writerow([
            "snr",
            "clean_accuracy",
            f"{attack_name}_accuracy",
            "drop",
            "attack_success_rate",
        ])

        for snr, row in zip(SNR_VALUES, data):
            clean, attack, drop, asr = row

            writer.writerow([
                snr,
                clean / 100,
                attack / 100,
                drop / 100,
                asr / 100,
            ])

    print(f"Saved: {path}")


